// HELPER FUNCTIONS FOR DETERMINISTIC CONTENT SELECTION

/**
 * Select a deterministic subset of items from a pool
 * Uses the seed to ensure same page always gets same content
 * @param pool Array of content items
 * @param seed Unique identifier for the page
 * @param count How many items to select
 */
export function selectFromPool<T>(pool: T[], seed: string, count: number): T[] {
  // Create deterministic hash from seed
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = ((hash << 5) - hash) + seed.charCodeAt(i);
    hash = hash & hash;
  }
  const absHash = Math.abs(hash);
  
  // Select 'count' items deterministically
  const selected: T[] = [];
  const poolSize = pool.length;
  
  for (let i = 0; i < count; i++) {
    const index = (absHash + i * 7) % poolSize; // Spread selections across pool
    selected.push(pool[index]);
  }
  
  return selected;
}

